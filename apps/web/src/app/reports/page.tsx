import Link from "next/link";
import { listReports } from "@/lib/store";
import { listSkills } from "@/lib/agents";
import { GenerateReport } from "@/components/Actions";

export const dynamic = "force-dynamic";

export default async function Reports({ searchParams }: { searchParams: Promise<{ q?: string }> }) {
  const { q } = await searchParams;
  const reports = listReports(q);
  const skills = listSkills();
  return (
    <div className="space-y-6">
      <header><h1 className="text-2xl font-semibold">Reports</h1><p className="text-muted text-sm">Generated by your existing Claude Code skills. Each is a dated snapshot: re-verify before relying on it.</p></header>
      <section><h2 className="font-medium mb-2 text-sm">Generate</h2>
        {skills.length ? <div className="flex flex-wrap gap-2">{skills.map((s) => <span key={s.slug} title={s.description}><GenerateReport skill={s.slug} /></span>)}</div> : <p className="text-muted text-sm">No skills found in .claude/skills.</p>}
        <p className="text-xs text-muted mt-2">Requires Claude Code to be signed in. Generation runs the real skill and can take several minutes.</p></section>
      <form><input name="q" defaultValue={q} className="input" placeholder="Search reports" aria-label="Search reports" /></form>
      {reports.length === 0 ? <p className="text-muted text-sm">No reports saved yet.</p> : (
        <ul className="card divide-y divide-border">{reports.map((r) => (
          <li key={r.id}><Link href={`/reports/${r.id}`} className="flex justify-between gap-3 p-3 hover:bg-bg text-sm"><span>{r.title} <span className="badge">{r.kind}</span></span><span className="text-xs text-muted whitespace-nowrap">{r.versions} version(s) · {r.latest?.slice(0, 10)}</span></Link></li>))}</ul>)}
    </div>
  );
}
